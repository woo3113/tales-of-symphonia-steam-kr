"""Enumerate the 27 length-rule sites and emit a C header for logger7 (patches the
   `mov R3,0xFE` instruction with a stub that also accepts EUC-KR as 2-byte)."""
import pefile, sys
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
TOS = r"D:\SteamLibrary\steamapps\common\Tales of Symphonia\TOS.exe"
OUTH = r"C:\Users\woo31\AppData\Local\Temp\opencode\tos_kr\work\lensites.h"
pe = pefile.PE(TOS); D = pe.__data__; IMG = pe.OPTIONAL_HEADER.ImageBase
secs = [(s.Name.rstrip(b"\x00").decode("latin1"), IMG + s.VirtualAddress, s.Misc_VirtualSize,
         s.PointerToRawData, s.SizeOfRawData) for s in pe.sections]


def va2off(v):
    for n, va, vs, pr, sr in secs:
        if va <= v < va + max(vs, sr):
            return pr + (v - va)


def off2va(o):
    for n, va, vs, pr, sr in secs:
        if pr <= o < pr + sr:
            return va + (o - pr)


def exec_ranges():
    for n, va, vs, pr, sr in secs:
        if n in (".text", ".dsstext"):
            yield va, min(vs, sr) if sr else vs


REG = ["eax", "ecx", "edx", "ebx", "esp", "ebp", "esi", "edi"]
entries = []
for va, size in exec_ranges():
    o = va2off(va)
    seg = D[o:o + size]
    k = -1
    while True:
        k = seg.find(b"\x8D", k + 1)
        if k < 0 or k + 6 >= len(seg):
            break
        if (seg[k + 1] >> 6) == 2 and (seg[k + 1] & 7) != 4 \
           and seg[k + 2] == 0xFF and seg[k + 3] == 0x7E and seg[k + 4] == 0 and seg[k + 5] == 0:
            L = va + k
            R = seg[k + 1] & 7
            # find `mov r32,0xFE` within next 40 bytes
            mp = None; R3 = None
            j = k + 6
            while j < k + 40:
                op = seg[j]
                if 0xB8 <= op <= 0xBF and seg[j + 1] == 0xFE and seg[j + 2] == 0 and seg[j + 3] == 0 and seg[j + 4] == 0:
                    mp = va + j; R3 = op - 0xB8; break
                j += 1
            # find `ja` after that (or after lea)
            start = (mp - va) + 5 if mp else k + 6
            ja = None
            j = start
            while j < start + 24:
                if seg[j] == 0x77:
                    rel = seg[j + 1]
                    if rel > 127: rel -= 256
                    ja = (va + j, 2, va + j + 2 + rel, va + j + 2); break
                if seg[j] == 0x0F and seg[j + 1] == 0x87:
                    rel = int.from_bytes(seg[j + 2:j + 6], "little", signed=True)
                    ja = (va + j, 6, va + j + 6 + rel, va + j + 6); break
                j += 1
            if mp and ja:
                entries.append(dict(lea=L, R=R, R3=R3, patch=mp, resume=mp + 5, ja=ja[0], len1=ja[2], len2=ja[3]))
            else:
                print("SKIP site 0x%X (R=%s) mp=%s ja=%s" % (L, REG[R], mp and hex(mp), ja))

print("sites:", len(entries))
for e in entries:
    print("  0x%06X R=%-3s R3=%-3s patch=0x%06X len1=0x%06X len2=0x%06X" %
          (e["lea"], REG[e["R"]], REG[e["R3"]], e["patch"], e["len1"], e["len2"]))

with open(OUTH, "w", encoding="ascii") as f:
    f.write("/* auto-generated by gen_lensites.py */\n")
    f.write("typedef struct { unsigned int patch, len1, len2; unsigned char R, R3; } LS;\n")
    f.write("static const LS g_ls[] = {\n")
    for e in entries:
        f.write("  { 0x%X, 0x%X, 0x%X, %d, %d },\n" % (e["patch"] - IMG, e["len1"] - IMG, e["len2"] - IMG, e["R"], e["R3"]))
    f.write("};\n")
    f.write("#define N_LS %d\n" % len(entries))
print("wrote", OUTH)
